#!/usr/bin/env bash
# validation-run-prep helper — idempotent prep for the worktree-based, three-harness dogen
# validation run on smoke-docs-1. The SKILL.md holds the judgment (confirmations, interpretation,
# prompt emission); this helper does the deterministic moves.
#
#   prepare.sh plan     # read-only: print what apply would do + preflight
#   prepare.sh verify   # read-only: assert the prep is sound (exit non-zero on any FAIL)
#   prepare.sh apply    # side-effecting: create worktrees, bake env files, refresh skills, commit
#
# Config via env (defaults resolve relative to this script's home in dogen-mvp-1):
#   DOGEN_REPO   up-to-date dogen checkout (default: this repo)
#   SMOKE        target repo, its own git repo (default: sibling smoke-docs-1)
#   WT_ROOT      where the 3 worktrees + env files live, OUTSIDE both repos
#                (default: sibling smoke-docs-worktrees)
#   BASE_TAG     the missing-file baseline tag
#   HARNESSES    space-separated: claude copilot opencode
#   FORCE=1      recreate existing worktrees/branches (default 0: skip existing, never clobber)
#   COMMIT_REFRESH=0  leave the skills refresh uncommitted (default 1: explicit-staged local commit)
set -u

# This script lives at <dogen-mvp-1>/.claude/skills/validation-run-prep/prepare.sh,
# so the repo root is three levels up and the siblings sit beside it.
script_dir="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
repo_root="$(CDPATH= cd -- "$script_dir/../../.." && pwd)"
parent_dir="$(CDPATH= cd -- "$repo_root/.." && pwd)"

DOGEN_REPO="${DOGEN_REPO:-$repo_root}"
SMOKE="${SMOKE:-$parent_dir/smoke-docs-1}"
WT_ROOT="${WT_ROOT:-$parent_dir/smoke-docs-worktrees}"
BASE_TAG="${BASE_TAG:-validation-base-v4}"
HARNESSES="${HARNESSES:-claude copilot opencode}"
FORCE="${FORCE:-0}"
COMMIT_REFRESH="${COMMIT_REFRESH:-1}"
DOGEN="$DOGEN_REPO/.venv/bin/dogen"

log() { printf '%s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

harness_root() {
  case "$1" in
    claude)   echo ".claude/skills" ;;
    copilot)  echo ".github/skills" ;;
    opencode) echo ".opencode/skills" ;;
    *)        die "unknown harness: $1" ;;
  esac
}

preflight() {
  [ -x "$DOGEN" ] || die "dogen not executable at $DOGEN (is the dogen-mvp-1 .venv built? run 'uv sync' there)"
  [ -d "$DOGEN_REPO/skills/dogen-plan" ] || die "canonical skills missing at $DOGEN_REPO/skills"
  git -C "$SMOKE" rev-parse --is-inside-work-tree >/dev/null 2>&1 || die "$SMOKE is not a git repo"
  git -C "$SMOKE" rev-parse -q --verify "refs/tags/$BASE_TAG" >/dev/null || die "tag $BASE_TAG not found in $SMOKE"
  git -C "$SMOKE" config user.name  >/dev/null 2>&1 || die "git user.name not set in $SMOKE"
  git -C "$SMOKE" config user.email >/dev/null 2>&1 || die "git user.email not set in $SMOKE"
}

cmd_plan() {
  preflight
  echo "validation-run-prep — plan"
  echo "  dogen         : $DOGEN"
  echo "  target repo   : $SMOKE"
  echo "  base tag      : $BASE_TAG ($(git -C "$SMOKE" rev-parse --short "$BASE_TAG"))"
  echo "  worktree root : $WT_ROOT   (FORCE=$FORCE  COMMIT_REFRESH=$COMMIT_REFRESH)"
  for h in $HARNESSES; do
    echo "  - $h -> $WT_ROOT/$h   branch validation/$h-wt   root $(harness_root "$h")"
  done
}

cmd_apply() {
  preflight
  mkdir -p "$WT_ROOT"
  for h in $HARNESSES; do
    wt="$WT_ROOT/$h"; br="validation/$h-wt"
    if git -C "$SMOKE" worktree list --porcelain | grep -qxF "worktree $wt"; then
      if [ "$FORCE" = "1" ]; then
        log "[$h] FORCE: removing existing worktree $wt"
        git -C "$SMOKE" worktree remove --force "$wt" || die "[$h] could not remove worktree"
      else
        log "[$h] worktree already at $wt — leaving as-is (set FORCE=1 to recreate)"
      fi
    fi
    if [ "$FORCE" = "1" ] && git -C "$SMOKE" show-ref -q --verify "refs/heads/$br"; then
      git -C "$SMOKE" branch -D "$br" >/dev/null 2>&1 || true
    fi
    if [ ! -e "$wt/.git" ]; then
      if git -C "$SMOKE" show-ref -q --verify "refs/heads/$br"; then
        git -C "$SMOKE" worktree add "$wt" "$br" >/dev/null || die "[$h] worktree add (existing branch) failed"
      else
        git -C "$SMOKE" worktree add "$wt" -b "$br" "$BASE_TAG" >/dev/null || die "[$h] worktree add (new branch) failed"
      fi
      log "[$h] worktree ready: $wt on $br"
    fi

    envf="$WT_ROOT/env-$h.sh"
    cat > "$envf" <<EOF
# dogen validation env for the $h leg (generated by validation-run-prep — do not hand-edit).
# Source this in the $h harness shell, rooted in $wt, before driving the loop:
#   source $envf
export PATH="$DOGEN_REPO/.venv/bin:\$PATH"
unset DOGEN_PROVIDER   # host-harness passenger resolution (mandatory for the multi-file unit)
echo "dogen: \$(command -v dogen)  |  DOGEN_PROVIDER=\${DOGEN_PROVIDER:-<unset>}"
EOF
    log "[$h] wrote $envf"

    ( cd "$wt" && "$DOGEN" skills install --harness "$h" --from "$DOGEN_REPO/skills" >/dev/null ) \
      || die "[$h] dogen skills install failed"
    log "[$h] skills refreshed from $DOGEN_REPO/skills"

    if [ "$COMMIT_REFRESH" = "1" ]; then
      git -C "$wt" add "$(harness_root "$h")" .dogen/skills-install.yaml >/dev/null 2>&1 || true
      if git -C "$wt" diff --cached --quiet; then
        log "[$h] skills already current — no refresh commit"
      else
        git -C "$wt" commit -q -m "chore(validation): refresh $h skills from dogen-mvp-1" \
          || die "[$h] refresh commit failed"
        log "[$h] committed skills refresh"
      fi
    fi
  done
  log "apply complete."
}

cmd_verify() {
  set +e
  preflight
  base_sha="$(git -C "$SMOKE" rev-parse "$BASE_TAG")"
  rc=0
  for h in $HARNESSES; do
    wt="$WT_ROOT/$h"; br="validation/$h-wt"; hrc=0
    ddir="$wt/docs/reference/definition-files"
    if [ ! -e "$wt/.git" ]; then log "FAIL [$h] worktree missing at $wt"; rc=1; continue; fi
    cur="$(git -C "$wt" rev-parse --abbrev-ref HEAD)"
    [ "$cur" = "$br" ] || { log "FAIL [$h] on '$cur', expected '$br'"; hrc=1; }
    git -C "$wt" merge-base --is-ancestor "$base_sha" HEAD || { log "FAIL [$h] HEAD does not contain $BASE_TAG"; hrc=1; }
    [ -f "$WT_ROOT/env-$h.sh" ] || { log "FAIL [$h] env file $WT_ROOT/env-$h.sh missing"; hrc=1; }
    dbin="$(PATH="$DOGEN_REPO/.venv/bin:$PATH" command -v dogen 2>/dev/null)"
    [ "$dbin" = "$DOGEN" ] || { log "FAIL [$h] dogen resolves to '$dbin', expected $DOGEN"; hrc=1; }
    [ ! -e "$ddir/workshop-definition.rst" ] || { log "FAIL [$h] workshop-definition.rst should be ABSENT (unit 1 missing-file state)"; hrc=1; }
    grep -q "runtime metadata model" "$ddir/sdk-definition.rst" 2>/dev/null || { log "FAIL [$h] sdk-definition divergence phrase missing (unit 2)"; hrc=1; }
    grep -q "project model" "$ddir/sdkcraft-definition.rst" 2>/dev/null || { log "FAIL [$h] sdkcraft-definition divergence phrase missing (unit 2)"; hrc=1; }
    ( cd "$wt" && "$DOGEN" unit ls 2>/dev/null | grep -q "No units" ) || log "WARN [$h] 'dogen unit ls' is not empty"
    ( cd "$wt" && "$DOGEN" skills status >/dev/null 2>&1 ) || log "WARN [$h] 'dogen skills status' returned non-zero"
    prov="$( cd "$wt" && "$DOGEN" provider show 2>/dev/null | tr -d '\n' )"
    [ -n "$prov" ] && log "INFO [$h] provider: $prov"
    if [ "$hrc" = "0" ]; then log "OK   [$h] worktree on $br from $BASE_TAG; dogen+skills+preconditions good"; else rc=1; fi
  done
  return "$rc"
}

case "${1:-}" in
  plan)   cmd_plan ;;
  apply)  cmd_apply ;;
  verify) cmd_verify ;;
  *) echo "usage: prepare.sh {plan|verify|apply}" >&2; exit 2 ;;
esac
